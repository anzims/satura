<?php

declare(strict_types=1);

namespace Anzims\Satura\Console;

use Anzims\Satura\Support\Palettes;
use Illuminate\Console\Command;

/**
 * Генерирует CSS с палитрами base/accent.
 *
 * Без --out печатает CSS в stdout, с --out пишет файл относительно
 * корня приложения. Файл подключается в app.css после satura.css,
 * чтобы переопределить палитры по умолчанию.
 */
final class ThemeCommand extends Command
{
    protected $signature = 'satura:theme
                            {--base= : Base palette, neutral colours}
                            {--accent= : Accent palette}
                            {--out= : Output file, relative to the app root; prints to stdout when omitted}
                            {--force : Overwrite the output file}';

    protected $description = 'Generate Satura palette CSS variables (--ui-base-*, --ui-accent-*)';

    public function handle(Palettes $palettes): int
    {
        $base = (string) ($this->option('base') ?? config('satura.theme.base', 'zinc'));
        $accent = (string) ($this->option('accent') ?? config('satura.theme.accent', 'blue'));

        foreach ([$base, $accent] as $name) {
            if (! $palettes->has($name)) {
                $this->components->error("Unknown palette [{$name}]. Available: ".implode(', ', $palettes->names()).'.');

                return self::FAILURE;
            }
        }

        $css = $this->css($palettes->shades($base), $palettes->shades($accent), $base, $accent);
        $out = (string) $this->option('out');

        if ($out === '') {
            $this->output->write($css);

            return self::SUCCESS;
        }

        $path = base_path($out);

        if (is_file($path) && ! $this->option('force')) {
            $this->components->error("File [{$path}] exists. Use --force to overwrite.");

            return self::FAILURE;
        }

        $directory = dirname($path);

        if (! is_dir($directory)) {
            mkdir($directory, 0777, true);
        }

        file_put_contents($path, $css);

        $this->components->info('Satura theme written to '.$path);

        return self::SUCCESS;
    }

    /**
     * @param  array<string, string>  $baseShades
     * @param  array<string, string>  $accentShades
     */
    private function css(array $baseShades, array $accentShades, string $baseName, string $accentName): string
    {
        $lines = [
            '/* Generated by php artisan satura:theme --base='.$baseName.' --accent='.$accentName.' */',
            ':root {',
        ];

        foreach ($baseShades as $shade => $value) {
            $lines[] = '    --ui-base-'.$shade.': '.$value.';';
        }

        $lines[] = '';

        foreach ($accentShades as $shade => $value) {
            $lines[] = '    --ui-accent-'.$shade.': '.$value.';';
        }

        $lines[] = '}';
        $lines[] = '';

        return implode("\n", $lines);
    }
}
